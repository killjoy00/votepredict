test('exact two original MPR-linked 3Play PDFs and currently verified original PDF content hashes, no Senate quote endorsement',()=>{
 assert.equal(receipts.sources.length,2);
 assert.equal(LEADS.length,2);
 for(let i=0;i<2;i++){
  const x=receipts.sources[i],p=LEADS[i];
  assert.equal(x.id,p.id);
  assert.equal(x.senator,p.senator);
  assert.equal(x.currentPublisherMprEpisode,p.episode);
  assert.equal(x.currentFirstPartyApm3PlayPdf,p.pdf);
  assert.equal(x.publisherDisplayedDay,p.displayedDay);
  assert.match(x.currentPdf.sha1Base32,/^[A-Z2-7]{32}$/);
  assert.match(x.currentPdf.rawSha256,/^[a-f0-9]{64}$/);
  assert.ok(x.currentPdf.bytes>30000&&x.currentPdf.bytes<50000);
  assert.equal(x.currentPdf.pdfMagicVersion,'1.4');
  assert.equal(x.currentMprHtml.exactPdfHrefSeen,true);
  assert.equal(x.currentMprHtml.visibleShortSpeakerLabelSeen,true);
  assert.equal(x.currentMprHtml.visibleSelectedShortUtteranceSeen,true);
  assert.equal(x.recordedSpeakerOrExactVerbatimQuoteHumanApproved,false);
  assert.equal(x.transcriptFirstPublicPostingUnknown,true);
 }
});
